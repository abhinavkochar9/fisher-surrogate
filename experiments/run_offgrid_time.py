"""Table 11 (reviewer R2.9) -- evaluation at temporal points different from training:
every neural surrogate is evaluated on the test grid shifted by half a grid step
(t_j + dt/2, last point dropped) and the change in E_traj is reported next to the on-grid value.

Also writes Table 11 in the manuscript layout to tables/final/table11_offgrid.tex.

Run:  python experiments/run_offgrid_time.py [--quick]
      python experiments/run_offgrid_time.py --tables-only     # rebuild the table from saved results
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from _baselines_common import fit_neural_ode
from _torch_common import (build_splits, config_dict, evaluate, fit_direct, fit_residual, resolve, seed_of,
                           torch_parser)
from fisher_surrogate import latex
from fisher_surrogate.common import final_tables_dir, out_dir, save_results
from fisher_surrogate.data import add_baseline_column
from fisher_surrogate.dynamics import solve_variance
from fisher_surrogate.metrics import summarize_seeds
from run_deeponet import fit_deeponet
from run_physics_informed import fit_pi


def shifted_test(test_df):
    t = np.sort(test_df["t"].unique())
    dt = t[1] - t[0]
    t_new = (t + dt / 2)[:-1]
    frames = []
    for pid, g in test_df.groupby("pair_id"):
        u0, eps = float(g.u0.iloc[0]), float(g.eps.iloc[0])
        frames.append(pd.DataFrame({"pair_id": pid, "u0": u0, "eps": eps, "t": t_new,
                                    "u_clean": solve_variance(u0, eps, np.concatenate([[0.0], t_new]), "adaptive")[1:]}))
    return pd.concat(frames, ignore_index=True), dt


# manuscript row name -> model label in the results
FINAL_ROWS = [("Direct MLP", "Direct MLP"), ("Residual MLP", "Residual MLP"),
              ("PI-Residual, $\\lambda=0.1$", "PI-Residual, $\\lambda=0.1$"), ("DeepONet-style", "DeepONet-style"),
              ("Neural ODE", "Neural ODE (full field)"), ("Residual Neural ODE", "Residual Neural ODE")]


def final_table(summary, quick=False):
    s = summary.set_index("model")
    n = {m: int(s.loc[m, "E_traj_on_grid_n"]) for _, m in FINAL_ROWS}
    lines = [f"% Table 11 (tab:offgrid_time): mean $\\pm$ 95% CI over S = {n['Direct MLP']} seeds "
             f"(S = {n['Neural ODE (full field)']} for the Neural ODE variants).",
             "% Generated by: python experiments/run_offgrid_time.py [--tables-only]",
             r"\begin{tabular}{lcc}", r"\toprule",
             r"Model & $E_{\mathrm{traj}}$ (grid) & $E_{\mathrm{traj}}$ ($+\Delta t/2$) \\", r"\midrule"]
    for row, model in FINAL_ROWS:
        r = s.loc[model]
        lines.append(f"{row} & {latex.cell(r.E_traj_on_grid_mean, r.E_traj_on_grid_ci)} & "
                     f"{latex.cell(r.E_traj_shifted_mean, r.E_traj_shifted_ci)} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    (final_tables_dir(quick) / "table11_offgrid.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    p = torch_parser(__doc__)
    p.add_argument("--node-seeds", type=int, default=5)
    p.add_argument("--tables-only", action="store_true", help="rebuild the tables from the results saved in --out")
    args = p.parse_args()
    if args.tables_only:
        final_table(pd.read_csv(out_dir(args, "offgrid_time") / "offgrid_time_summary.csv"), args.quick)
        return
    n_seeds, dcfg, tcfg, mkw = resolve(args)
    node_seeds = 1 if args.quick else args.node_seeds
    if args.quick:
        tcfg.epochs, tcfg.patience = 30, 10
    out = out_dir(args, "offgrid_time")
    train_df, val_df, test_df = build_splits(dcfg)
    shifted, dt = shifted_test(test_df)
    rows = []
    for i in range(n_seeds):
        s = seed_of(i)
        print(f"seed {i:02d}", flush=True)
        fits = {"Direct MLP": fit_direct(train_df, val_df, s, tcfg),
                "Residual MLP": fit_residual(train_df, val_df, s, tcfg),
                "PI-Residual, $\\lambda=0.1$": fit_pi(train_df, val_df, 0.1, s, tcfg),
                "DeepONet-style": fit_deeponet(train_df, val_df, s, 64, tcfg)}
        if i < node_seeds:
            fits["Neural ODE (full field)"] = fit_neural_ode(train_df, val_df, s, tcfg, residual=False)
            fits["Residual Neural ODE"] = fit_neural_ode(train_df, val_df, s, tcfg, residual=True)
        for name, fit in fits.items():
            on = evaluate(fit, test_df, mkw)[0]["E_traj"]
            off = evaluate(fit, shifted, mkw)[0]["E_traj"]
            rows.append({"model": name, "seed": i, "E_traj_on_grid": on, "E_traj_shifted": off,
                         "relative_change": (off - on) / on})
    seed_df = pd.DataFrame(rows)
    summary = summarize_seeds(seed_df, ["model"], metrics=["E_traj_on_grid", "E_traj_shifted", "relative_change"])
    lines = [r"\begin{table}[t]", r"\centering", r"\small",
             rf"\caption{{Trajectory error on the training-aligned test grid and on a grid shifted by $\Delta t/2 = {dt/2:.4f}$ "
             rf"(mean $\pm$ 95\% CI over $S={n_seeds}$ seeds; $S={node_seeds}$ for Neural ODE variants).}}",
             r"\label{tab:offgrid_time}", r"\begin{tabular}{lccc}", r"\hline",
             r"Model & $E_{\mathrm{traj}}$ (on grid) & $E_{\mathrm{traj}}$ ($t_j+\Delta t/2$) & relative change \\", r"\hline"]
    for _, r in summary.iterrows():
        lines.append(f"{r['model']} & {latex.sci_ci(r['E_traj_on_grid_mean'], r['E_traj_on_grid_ci'])} & "
                     f"{latex.sci_ci(r['E_traj_shifted_mean'], r['E_traj_shifted_ci'])} & {100 * r['relative_change_mean']:+.1f}\\% \\\\")
    lines += [r"\hline", r"\end{tabular}", r"\end{table}"]
    save_results(out, "offgrid_time", seed_df, summary, "\n".join(lines), config_dict(args, dcfg, tcfg, n_seeds, mkw, dt=dt))
    final_table(summary, args.quick)


if __name__ == "__main__":
    main()
