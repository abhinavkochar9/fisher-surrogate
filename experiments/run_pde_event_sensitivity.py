"""Round 2 (Reviewer 3, M4): sensitivity of the event times T_acc and T_x to the two diagnostic parameters
that the refinement study of Table C.21 keeps fixed -- the output-time sampling (n_out points on
[0, T_max]) and the uniform background added to the initial density before normalization.

The BDF step sequence does not depend on the output times (scipy solve_ivp evaluates its dense output at
t_eval), so varying n_out isolates the event-interpolation error: T_acc is the linear interpolation of
u(t) at u = 1 and T_x that of the first sign change of D_x(t) between output points.

  study 'n_out'       reference discretization (L = 6, N_x = 512, max step 1e-4), background 1e-8,
                      n_out in {126, 251, 501, 1001, 2001, 4001} (output spacing 0.04 ... 0.00125)
  study 'background'  reference discretization, n_out = 501, background in {1e-10, ..., 1e-6}
  study 'refinement'  the (N_x, dt) x L levels of Table C.21 at n_out = 501 (as published) and 4001,
                      with the Richardson intercept d0 of T_x - T_acc computed by the same rule as
                      run_pde_nongaussian.py at each n_out

Run:  python experiments/run_pde_event_sensitivity.py [--families Gaussian "Asymmetric bimodal"] [--workers 4]
      python experiments/run_pde_event_sensitivity.py --tables-only
"""
from __future__ import annotations

import json
import os
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.interpolate import CubicSpline
from scipy.optimize import brentq

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from fisher_surrogate import pde  # noqa: E402
from fisher_surrogate.common import experiment_parser, final_tables_dir, out_dir  # noqa: E402
from run_pde_nongaussian import richardson_intercepts  # noqa: E402

N_OUT = (126, 251, 501, 1001, 2001, 4001)
BACKGROUNDS = (1e-10, 1e-9, 1e-8, 1e-7, 1e-6)
REFINE_N_OUT = (501, 4001)
REF = (6.0, 512, 1e-4)


def cubic_event(t, y, level):
    """First upward crossing of ``level`` by a cubic spline through the output samples (Brent root in the
    bracketing interval); the published diagnostics interpolate linearly between the same samples."""
    k = np.where((y[:-1] < level) & (y[1:] >= level))[0]
    if len(k) == 0:
        return np.nan
    k = int(k[0])
    cs = CubicSpline(t, y)
    return float(brentq(lambda s: float(cs(s)) - level, t[k], t[k + 1], xtol=1e-14))


def one(job):
    study, fam, L, nx, dt, n_out, bg = job
    res = pde.run_family(fam, eps=0.1, u0=0.36, L=L, nx=nx, dt=dt, t_long=None, n_out=n_out, background=bg)
    ta_c, tx_c = cubic_event(res.t, res.u, 1.0), cubic_event(res.t, res.Dx, 0.0)
    return {"study": study, "family": fam, "L": L, "nx": nx, "dt": dt, "n_out": n_out, "background": bg,
            "u0_actual": float(res.u[0]), "T_acc": res.T_acc, "T_x": res.T_x, "d": res.T_x - res.T_acc,
            "T_acc_cubic": ta_c, "T_x_cubic": tx_c, "d_cubic": tx_c - ta_c}


def jobs(families):
    out = []
    for fam in families:
        out += [("n_out", fam, *REF, n, 1e-8) for n in N_OUT]
        out += [("background", fam, *REF, 501, bg) for bg in BACKGROUNDS]
        out += [("refinement", fam, L, nx, dt, n, 1e-8) for n in REFINE_N_OUT for L in pde.DOMAINS
                for nx, dt in pde.REFINEMENT_LEVELS.values()]
    return out


def tables(out, quick=False):
    df = pd.read_csv(out / "event_sensitivity.csv")
    lines = ["% Event-time sensitivity (Reviewer 3, M4). eps = 0.1, u0 = 0.36.",
             "% Generated by: python experiments/run_pde_event_sensitivity.py --tables-only"]
    summary = []
    for fam, g in df.groupby("family", sort=False):
        n = g[g.study == "n_out"].sort_values("n_out")
        ref, best = n[n.n_out == 501].iloc[0], n.iloc[-1]
        b = g[g.study == "background"].sort_values("background")
        lines.append(f"% {fam}: n_out sweep (T_acc, T_x, d = T_x - T_acc) at L=6, N_x=512")
        for _, r in n.iterrows():
            lines.append(f"%   n_out={int(r.n_out):5d}  linear: T_acc={r.T_acc:.7f} T_x={r.T_x:.7f} d={r.d:+.4e} | "
                         f"cubic: T_acc={r.T_acc_cubic:.7f} T_x={r.T_x_cubic:.7f} d={r.d_cubic:+.4e}")
        lines.append(f"% {fam}: background sweep at n_out=501")
        for _, r in b.iterrows():
            lines.append(f"%   background={r.background:.0e}  u0={r.u0_actual:.9f}  T_acc={r.T_acc:.7f}  T_x={r.T_x:.7f}  d={r.d:+.3e}")
        row = {"family": fam,
               "interp_err_T_acc_501": float(abs(ref.T_acc - best.T_acc)), "interp_err_T_x_501": float(abs(ref.T_x - best.T_x)),
               "interp_err_d_501": float(abs(ref.d - best.d)),
               "bg_range_T_acc": float(b.T_acc.max() - b.T_acc.min()), "bg_range_T_x": float(b.T_x.max() - b.T_x.min()),
               "bg_range_d": float(b.d.max() - b.d.min())}
        row["interp_err_d_501_cubic"] = float(abs(ref.d_cubic - best.d_cubic))
        for n_out in REFINE_N_OUT:
            conv = g[(g.study == "refinement") & (g.n_out == n_out)]
            ic = richardson_intercepts(conv).iloc[0]
            row[f"d0_{n_out}"], row[f"u_{n_out}"], row[f"ratio_{n_out}"] = ic.d0, ic.u, ic.abs_d0_over_u
            cc = conv.assign(T_x=conv.T_x_cubic, T_acc=conv.T_acc_cubic)
            ic = richardson_intercepts(cc).iloc[0]
            row[f"d0c_{n_out}"], row[f"uc_{n_out}"], row[f"ratioc_{n_out}"] = ic.d0, ic.u, ic.abs_d0_over_u
        summary.append(row)
    s = pd.DataFrame(summary)
    s.to_csv(out / "event_sensitivity_summary.csv", index=False)
    lines.append("% Summary: interpolation error at n_out = 501 (difference to n_out = 4001); range over the background sweep;")
    lines.append("% Richardson intercept d0 +/- u (rule of Table C.21) at n_out = 501 and 4001, linear (published) and cubic")
    lines.append("% event interpolation. Columns: family & interp. error T_acc, T_x, d (linear, n_out 501) & d (cubic, 501) &")
    lines.append("% background range T_acc, T_x, d & d0 linear 501 & d0 linear 4001 & d0 cubic 501 & d0 cubic 4001")
    for _, r in s.iterrows():
        lines.append(f"{r.family} & {r.interp_err_T_acc_501:.1e} & {r.interp_err_T_x_501:.1e} & {r.interp_err_d_501:.1e} & "
                     f"{r.interp_err_d_501_cubic:.1e} & {r.bg_range_T_acc:.1e} & {r.bg_range_T_x:.1e} & {r.bg_range_d:.1e} & "
                     f"${r.d0_501:+.1e}\\pm{r.u_501:.1e}$ & ${r.d0_4001:+.1e}\\pm{r.u_4001:.1e}$ & "
                     f"${r.d0c_501:+.1e}\\pm{r.uc_501:.1e}$ & ${r.d0c_4001:+.1e}\\pm{r.uc_4001:.1e}$ \\\\")
    (final_tables_dir(quick) / "round2_pde_event_sensitivity.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


def main():
    p = experiment_parser(__doc__)
    p.add_argument("--families", nargs="*", default=["Gaussian", "Asymmetric bimodal"])
    p.add_argument("--workers", type=int, default=4)
    p.add_argument("--tables-only", action="store_true")
    args = p.parse_args()
    out = out_dir(args, "pde_event_sensitivity")
    if not args.tables_only:
        os.environ.setdefault("OMP_NUM_THREADS", "1")
        todo = jobs(args.families)
        if args.quick:
            todo = [j for j in todo if j[3] <= 512 and j[5] <= 1001][:6]
        with ProcessPoolExecutor(max_workers=args.workers) as ex:
            rows = list(ex.map(one, todo))
        pd.DataFrame(rows).to_csv(out / "event_sensitivity.csv", index=False)
        (out / "event_sensitivity_config.json").write_text(json.dumps(
            {"args": vars(args), "n_out": N_OUT, "backgrounds": BACKGROUNDS, "refine_n_out": REFINE_N_OUT,
             "reference": REF, "levels": pde.REFINEMENT_LEVELS, "domains": pde.DOMAINS}, indent=2, default=str))
        if args.quick:
            return
    tables(out, args.quick)


if __name__ == "__main__":
    main()
